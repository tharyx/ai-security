import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import hashcrack as c  # noqa: E402

leaked = {f"user{i}": c.md5_hex(pw) for i, pw in enumerate(c.LAB_PASSWORDS, 1)}
print("=== Leaked unsalted MD5 table (generated by the lab) ===")
for u, h in leaked.items():
    print(f"  {u}: {h}")

print("\n=== Dictionary attack ===")
print("  cracked:", c.dictionary_attack(leaked, c.TINY_DICTIONARY))

print("\n=== Brute force (lowercase, up to 3 chars) ===")
pw, tries = c.brute_force(leaked["user3"], max_len=3)
print(f"  user3 -> {pw!r} after {tries} tries")

print("\n=== Combinations (word+suffix, word+word) ===")
for u in ("user4", "user5"):
    pw, tries = c.combinations_attack(leaked[u])
    print(f"  {u} -> {pw!r} after {tries} tries")

print("\n=== Salted slow hashes ===")
a = c.pbkdf2_hash("sunshine")
b = c.pbkdf2_hash("sunshine")
print("  same password, two PBKDF2 hashes differ:", a != b)
print("  ", a[:60] + "...")
md5_rate = c.guesses_per_second(c.md5_hex)
pb_rate = c.guesses_per_second(lambda p: c.pbkdf2_hash(p, b"0" * 16))
print(f"  MD5 guesses/s on this machine         : {md5_rate:,.0f}")
print(f"  PBKDF2-SHA256 600k guesses/s (1 core) : {pb_rate:,.1f}")
print(f"  slowdown factor                       : ~{md5_rate / max(pb_rate, 0.01):,.0f}x")
