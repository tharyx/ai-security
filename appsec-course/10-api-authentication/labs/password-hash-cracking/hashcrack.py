"""Cracking weak password hashes (dictionary, brute force, combinations) and
why salted slow hashes resist it.

Covers "Weak Password Storage", "Cracking Weak Password Hashes With
Dictionaries" and "Cracking Weak Password Hashes With Bruteforce And
Combinations". Every hash cracked here is generated by the lab itself from a
tiny built-in list of lab passwords. Brute-force keyspaces are tiny (at most
4 lowercase letters) so tests stay fast.

Weak storage:   unsalted MD5 / SHA-1 (fast, identical passwords -> identical hashes)
Strong storage: salted PBKDF2-HMAC-SHA256 or scrypt via hashlib (slow, unique salt)
(Argon2id is the first choice in production but is not in the standard library.)

Only test systems you own or have written permission to test.
"""
from __future__ import annotations

import hashlib
import hmac
import itertools
import os
import string
import time

LAB_PASSWORDS = ["sunshine", "dragon", "abc", "summer2024", "bluecat"]
TINY_DICTIONARY = ["123456", "password", "sunshine", "dragon", "letmein", "monkey"]
COMBO_WORDS = ["summer", "winter", "blue", "red", "cat", "dog"]
COMBO_SUFFIXES = ["", "1", "123", "2024", "!"]


# --- weak storage ----------------------------------------------------------
def md5_hex(pw: str) -> str:
    return hashlib.md5(pw.encode()).hexdigest()


def sha1_hex(pw: str) -> str:
    return hashlib.sha1(pw.encode()).hexdigest()


# --- strong storage --------------------------------------------------------
def pbkdf2_hash(pw: str, salt: bytes | None = None, iterations: int = 600_000) -> str:
    """Return 'pbkdf2_sha256$iter$salthex$hashhex'. ~600k iterations per OWASP (verify)."""
    salt = salt if salt is not None else os.urandom(16)
    dk = hashlib.pbkdf2_hmac("sha256", pw.encode(), salt, iterations)
    return f"pbkdf2_sha256${iterations}${salt.hex()}${dk.hex()}"


def pbkdf2_verify(pw: str, stored: str) -> bool:
    _, it, salt_hex, hash_hex = stored.split("$")
    dk = hashlib.pbkdf2_hmac("sha256", pw.encode(), bytes.fromhex(salt_hex), int(it))
    return hmac.compare_digest(dk.hex(), hash_hex)


def scrypt_hash(pw: str, salt: bytes | None = None, n: int = 2**14, r: int = 8, p: int = 1) -> str:
    salt = salt if salt is not None else os.urandom(16)
    dk = hashlib.scrypt(pw.encode(), salt=salt, n=n, r=r, p=p, dklen=32)
    return f"scrypt${n}${r}${p}${salt.hex()}${dk.hex()}"


def scrypt_verify(pw: str, stored: str) -> bool:
    _, n, r, p, salt_hex, hash_hex = stored.split("$")
    dk = hashlib.scrypt(pw.encode(), salt=bytes.fromhex(salt_hex),
                        n=int(n), r=int(r), p=int(p), dklen=32)
    return hmac.compare_digest(dk.hex(), hash_hex)


# --- attacks on fast unsalted hashes ---------------------------------------
def dictionary_attack(target_hashes: dict, wordlist: list, hash_fn=md5_hex) -> dict:
    """target_hashes: user -> hex. Hash each word ONCE, match all users at once
    (possible only because there is no salt)."""
    table = {hash_fn(w): w for w in wordlist}
    return {user: table[h] for user, h in target_hashes.items() if h in table}


def brute_force(target_hash: str, max_len: int = 3, hash_fn=md5_hex,
                alphabet: str = string.ascii_lowercase):
    """Try every lowercase string up to max_len (capped at 4). Returns (pw, tries)."""
    if max_len > 4:
        raise ValueError("lab cap: keyspace limited to 4 lowercase characters")
    tries = 0
    for length in range(1, max_len + 1):
        for combo in itertools.product(alphabet, repeat=length):
            tries += 1
            guess = "".join(combo)
            if hash_fn(guess) == target_hash:
                return guess, tries
    return None, tries


def combinations_attack(target_hash: str, words: list = COMBO_WORDS,
                        suffixes: list = COMBO_SUFFIXES, hash_fn=md5_hex):
    """Word + word and word + suffix combinations (a hybrid/rule attack)."""
    tries = 0
    candidates = itertools.chain(
        (w + s for w in words for s in suffixes),
        (a + b for a in words for b in words),
    )
    for guess in candidates:
        tries += 1
        if hash_fn(guess) == target_hash:
            return guess, tries
    return None, tries


def guesses_per_second(hash_fn, seconds: float = 0.2) -> float:
    """Rough local speed of a hash function, to compare costs."""
    count, start = 0, time.perf_counter()
    while time.perf_counter() - start < seconds:
        hash_fn("guess%d" % count)
        count += 1
    return count / (time.perf_counter() - start)
